create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  car_id bigint not null,
  car_label text not null,
  event_type text not null check (event_type in ('stock_received', 'stock_adjustment', 'sale', 'status_change', 'car_deleted')),
  quantity_change integer not null default 0,
  stock_before integer not null default 0,
  stock_after integer not null default 0,
  sale_price numeric(12, 2),
  note text,
  actor_id uuid references auth.users(id) on delete set null,
  actor_email text,
  created_at timestamptz not null default now()
);

create index if not exists inventory_movements_created_at_idx
  on public.inventory_movements (created_at desc);
create index if not exists inventory_movements_car_id_idx
  on public.inventory_movements (car_id, created_at desc);
create index if not exists inventory_movements_event_type_idx
  on public.inventory_movements (event_type, created_at desc);

alter table public.inventory_movements enable row level security;

create policy "Signed-in users can read inventory history"
  on public.inventory_movements for select to authenticated
  using (auth.uid() is not null);

create or replace function public.log_inventory_movement()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  event_name text;
  before_stock integer := 0;
  after_stock integer := 0;
  label text;
  actor uuid := auth.uid();
  sale_amount numeric(12, 2);
begin
  if tg_op = 'INSERT' then
    event_name := 'stock_received';
    after_stock := greatest(coalesce(new.stock, 0), 0);
    label := concat_ws(' ', new.brand, new.model);
  elsif tg_op = 'DELETE' then
    event_name := 'car_deleted';
    before_stock := greatest(coalesce(old.stock, 0), 0);
    label := concat_ws(' ', old.brand, old.model);
  else
    before_stock := greatest(coalesce(old.stock, 0), 0);
    after_stock := greatest(coalesce(new.stock, 0), 0);
    label := concat_ws(' ', new.brand, new.model);
    if before_stock is distinct from after_stock then
      event_name := coalesce(nullif(current_setting('app.inventory_event_type', true), ''), 'stock_adjustment');
      if event_name = 'sale' then
        sale_amount := coalesce(nullif(current_setting('app.inventory_sale_price', true), '')::numeric, new.price);
      end if;
    elsif old.status is distinct from new.status then
      event_name := 'status_change';
    else
      return new;
    end if;
  end if;

  insert into public.inventory_movements (
    car_id, car_label, event_type, quantity_change, stock_before,
    stock_after, sale_price, note, actor_id, actor_email
  ) values (
    case when tg_op = 'DELETE' then old.id else new.id end,
    label,
    event_name,
    after_stock - before_stock,
    before_stock,
    after_stock,
    sale_amount,
    nullif(left(current_setting('app.inventory_note', true), 500), ''),
    actor,
    auth.jwt() ->> 'email'
  );

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

drop trigger if exists cars_inventory_movement_trigger on public.cars;
create trigger cars_inventory_movement_trigger
  after insert or update of stock, status or delete on public.cars
  for each row execute function public.log_inventory_movement();

create or replace function public.record_car_sale(
  p_car_id bigint,
  p_quantity integer default 1,
  p_sale_price numeric default null,
  p_note text default null
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if p_quantity is null or p_quantity < 1 then
    raise exception 'Quantity must be at least one';
  end if;
  if p_sale_price is not null and p_sale_price < 0 then
    raise exception 'Sale price cannot be negative';
  end if;

  perform set_config('app.inventory_event_type', 'sale', true);
  perform set_config('app.inventory_sale_price', coalesce(p_sale_price::text, ''), true);
  perform set_config('app.inventory_note', coalesce(p_note, ''), true);

  update public.cars
  set stock = stock - p_quantity,
      status = case when stock - p_quantity = 0 then 'sold' else status end
  where id = p_car_id
    and coalesce(stock, 0) >= p_quantity
    and coalesce(status, '') <> 'sold';

  if not found then
    raise exception 'Car is unavailable or stock is insufficient';
  end if;
end;
$$;

revoke all on function public.record_car_sale(bigint, integer, numeric, text) from public, anon;
grant execute on function public.record_car_sale(bigint, integer, numeric, text) to authenticated;
