create table if not exists public.customer_inquiries (
  id bigint generated by default as identity primary key,
  car_id text not null,
  car_label text not null,
  customer_name text not null check (char_length(trim(customer_name)) between 1 and 100),
  phone text not null check (char_length(trim(phone)) between 6 and 30),
  line_id text check (line_id is null or char_length(line_id) <= 50),
  message text not null check (char_length(trim(message)) between 1 and 2000),
  status text not null default 'new' check (status in ('new', 'contacted', 'closed')),
  created_at timestamptz not null default now()
);

alter table public.customer_inquiries enable row level security;

create policy "Anyone can submit a customer inquiry"
  on public.customer_inquiries
  for insert
  to anon, authenticated
  with check (
    status = 'new'
    and char_length(trim(customer_name)) between 1 and 100
    and char_length(trim(phone)) between 6 and 30
    and char_length(trim(message)) between 1 and 2000
  );

create policy "Signed-in admins can read customer inquiries"
  on public.customer_inquiries
  for select
  to authenticated
  using (auth.role() = 'authenticated');

create policy "Signed-in admins can update customer inquiries"
  on public.customer_inquiries
  for update
  to authenticated
  using (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

create index if not exists customer_inquiries_created_at_idx
  on public.customer_inquiries (created_at desc);

create index if not exists customer_inquiries_status_idx
  on public.customer_inquiries (status);
